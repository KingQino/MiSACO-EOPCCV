function General = CollectEOPCCVResults(statsRoot)
%CollectEOPCCVResults Collect per-problem MiSACO stats into one summary.

    if nargin < 1 || isempty(statsRoot)
        statsRoot = fullfile(fileparts(mfilename('fullpath')),'MiSACO','stats');
    end

    if ~isfolder(statsRoot)
        error('CollectEOPCCVResults:StatsRootNotFound', ...
            'Stats root does not exist: %s', statsRoot);
    end

    rows = {};
    for problemId = 1:30
        instanceName = sprintf('F%d',problemId);
        instanceDir  = fullfile(statsRoot,instanceName);
        if ~isfolder(instanceDir)
            continue;
        end

        T = LoadSeedStats(instanceDir,instanceName);
        if isempty(T)
            continue;
        end
        WriteInstanceStats(instanceDir,instanceName,T);

        [minBest,bestIdx] = min(T.BestObjective);
        rows(end+1,:) = { ...
            instanceName, ...
            height(T), ...
            minBest, ...
            T.Seed(bestIdx), ...
            mean(T.BestObjective), ...
            std(T.BestObjective), ...
            max(T.BestObjective), ...
            mean(T.Runtime), ...
            mean(T.TotalFE), ...
            mean(T.RBFImprovements), ...
            mean(T.RFImprovements), ...
            mean(T.RandomImprovements), ...
            mean(T.BasinHopImprovements,'omitnan'), ...
            mean(T.BasinHopExploreImprovements,'omitnan'), ...
            mean(T.BasinTriggerAttempts,'omitnan'), ...
            mean(T.BasinTriggers,'omitnan'), ...
            mean(T.BasinVetoes,'omitnan'), ...
            mean(T.BasinExploreTriggers,'omitnan'), ...
            mean(T.BasinAlignmentSamples,'omitnan'), ...
            mean(T.BasinAlignmentGuidedAttempts,'omitnan'), ...
            mean(T.BasinCandidateVetoes,'omitnan'), ...
            mean(T.BasinRandomFallbacks,'omitnan'), ...
            mean(T.EnsembleImprovements,'omitnan'), ...
            mean(T.LocalSearchImprovements)}; %#ok<AGROW>
    end

    if isempty(rows)
        error('CollectEOPCCVResults:NoStatsFound', ...
            'No stats.F*.csv files were found under %s.', statsRoot);
    end

    General = cell2table(rows, 'VariableNames', { ...
        'Instance', ...
        'CompletedSeeds', ...
        'BestObjective', ...
        'BestSeed', ...
        'MeanBestObjective', ...
        'StdBestObjective', ...
        'WorstBestObjective', ...
        'MeanRuntime', ...
        'MeanTotalFE', ...
        'MeanRBFImprovements', ...
        'MeanRFImprovements', ...
        'MeanRandomImprovements', ...
        'MeanBasinHopImprovements', ...
        'MeanBasinHopExploreImprovements', ...
        'MeanBasinTriggerAttempts', ...
        'MeanBasinTriggers', ...
        'MeanBasinVetoes', ...
        'MeanBasinExploreTriggers', ...
        'MeanBasinAlignmentSamples', ...
        'MeanBasinAlignmentGuidedAttempts', ...
        'MeanBasinCandidateVetoes', ...
        'MeanBasinRandomFallbacks', ...
        'MeanEnsembleImprovements', ...
        'MeanLocalSearchImprovements'});

    writetable(General, fullfile(statsRoot,'general.csv'));
    save(fullfile(statsRoot,'general.mat'),'General');
    WriteGeneralText(fullfile(statsRoot,'general.txt'),General);

    fprintf('Collected %d instance summaries into %s\n',height(General),statsRoot);
end


function T = LoadSeedStats(instanceDir, instanceName)
    rows = [];
    seedDirs = dir(instanceDir);
    seedDirs = seedDirs([seedDirs.isdir]);
    seedDirs = seedDirs(~ismember({seedDirs.name},{'.','..'}));

    for k = 1:numel(seedDirs)
        seedName = seedDirs(k).name;
        if isempty(regexp(seedName,'^\d+$','once'))
            continue;
        end

        seed = str2double(seedName);
        historyFile = fullfile(instanceDir,seedName, ...
            sprintf('history.%s.seed%d.mat',instanceName,seed));
        summaryFile = fullfile(instanceDir,seedName, ...
            sprintf('summary.%s.seed%d.txt',instanceName,seed));
        if ~isfile(historyFile)
            continue;
        end
        if ~isfile(summaryFile)
            warning('CollectEOPCCVResults:IncompleteSeed', ...
                'Skipping incomplete seed without summary file: %s seed %d', ...
                instanceName,seed);
            continue;
        end

        data = load(historyFile,'RunSummary');
        if ~isfield(data,'RunSummary')
            continue;
        end

        rows = [rows; SummaryToRow(data.RunSummary,seed)]; %#ok<AGROW>
    end

    if isempty(rows)
        T = table();
        return;
    end

    T = struct2table(rows);
    T = sortrows(T,'Seed');
end



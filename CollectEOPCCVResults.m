function General = CollectEOPCCVResults(statsRoot)
%CollectEOPCCVResults Collect per-problem MiSACO stats into one summary.

    if nargin < 1 || isempty(statsRoot)
        statsRoot = fullfile(fileparts(mfilename('fullpath')),'MiSACO','stats');
    end

    if ~isfolder(statsRoot)
        error('CollectEOPCCVResults:StatsRootNotFound', ...
            'Stats root does not exist: %s', statsRoot);
    end

    rows = {};
    for problemId = 1:30
        instanceName = sprintf('F%d',problemId);
        instanceDir  = fullfile(statsRoot,instanceName);
        statsPath    = fullfile(instanceDir,sprintf('stats.%s.csv',instanceName));
        if ~isfile(statsPath)
            continue;
        end

        T = readtable(statsPath);
        if isempty(T)
            continue;
        end

        [minBest,bestIdx] = min(T.BestObjective);
        rows(end+1,:) = { ...
            instanceName, ...
            height(T), ...
            minBest, ...
            T.Seed(bestIdx), ...
            mean(T.BestObjective), ...
            std(T.BestObjective), ...
            max(T.BestObjective), ...
            mean(T.Runtime), ...
            mean(T.TotalFE), ...
            mean(T.RBFImprovements), ...
            mean(T.RFImprovements), ...
            mean(T.RandomImprovements), ...
            mean(T.LocalSearchImprovements)}; %#ok<AGROW>
    end

    if isempty(rows)
        error('CollectEOPCCVResults:NoStatsFound', ...
            'No stats.F*.csv files were found under %s.', statsRoot);
    end

    General = cell2table(rows, 'VariableNames', { ...
        'Instance', ...
        'CompletedSeeds', ...
        'BestObjective', ...
        'BestSeed', ...
        'MeanBestObjective', ...
        'StdBestObjective', ...
        'WorstBestObjective', ...
        'MeanRuntime', ...
        'MeanTotalFE', ...
        'MeanRBFImprovements', ...
        'MeanRFImprovements', ...
        'MeanRandomImprovements', ...
        'MeanLocalSearchImprovements'});

    writetable(General, fullfile(statsRoot,'general.csv'));
    save(fullfile(statsRoot,'general.mat'),'General');
    WriteGeneralText(fullfile(statsRoot,'general.txt'),General);

    fprintf('Collected %d instance summaries into %s\n',height(General),statsRoot);
end


function WriteGeneralText(filePath, General)
    fileID = fopen(filePath,'w');
    if fileID == -1
        error('CollectEOPCCVResults:GeneralFileOpenError', ...
            'Could not open %s for writing.', filePath);
    end
    cleaner = onCleanup(@() fclose(fileID));

    fprintf(fileID,'Instance,Seeds,Best,BestSeed,Mean,Std,Worst,MeanRuntime\n');
    for i = 1:height(General)
        fprintf(fileID,'%s,%d,%.12g,%d,%.12g,%.12g,%.12g,%.6f\n', ...
            General.Instance{i}, ...
            General.CompletedSeeds(i), ...
            General.BestObjective(i), ...
            General.BestSeed(i), ...
            General.MeanBestObjective(i), ...
            General.StdBestObjective(i), ...
            General.WorstBestObjective(i), ...
            General.MeanRuntime(i));
    end

    clear cleaner;
end

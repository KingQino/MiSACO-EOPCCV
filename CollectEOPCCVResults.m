function WriteInstanceStats(instanceDir, instanceName, seedTable)
    writetable(seedTable, fullfile(instanceDir,sprintf('stats.%s.csv',instanceName)));
    save(fullfile(instanceDir,sprintf('stats.%s.mat',instanceName)),'seedTable');

    filePath = fullfile(instanceDir,sprintf('stats.%s.txt',instanceName));
    fileID = fopen(filePath,'w');
    if fileID == -1
        error('CollectEOPCCVResults:StatsFileOpenError', ...
            'Could not open %s for writing.', filePath);
    end
    cleaner = onCleanup(@() fclose(fileID));
    fprintf(fileID,'Instance %s\n',instanceName);
    fprintf(fileID,'Completed seeds %d\n',height(seedTable));
    fprintf(fileID,'Min %.12g\n',min(seedTable.BestObjective));
    fprintf(fileID,'Mean %.12g\n',mean(seedTable.BestObjective));
    fprintf(fileID,'Std %.12g\n',std(seedTable.BestObjective));
    fprintf(fileID,'Max %.12g\n',max(seedTable.BestObjective));
    fprintf(fileID,'MeanRuntime %.6f\n',mean(seedTable.Runtime));
    clear cleaner;
end


function WriteGeneralText(filePath, General)
    fileID = fopen(filePath,'w');
    if fileID == -1
        error('CollectEOPCCVResults:GeneralFileOpenError', ...
            'Could not open %s for writing.', filePath);
    end
    cleaner = onCleanup(@() fclose(fileID));

    fprintf(fileID,'Instance,Seeds,Best,BestSeed,Mean,Std,Worst,MeanRuntime,MeanBasinHopImprovements,MeanBasinHopExploreImprovements,MeanBasinTriggerAttempts,MeanBasinTriggers,MeanBasinVetoes,MeanBasinExploreTriggers,MeanBasinAlignmentSamples,MeanBasinAlignmentGuidedAttempts,MeanBasinCandidateVetoes,MeanBasinRandomFallbacks,MeanEnsembleImprovements\n');
    for i = 1:height(General)
        fprintf(fileID,'%s,%d,%.12g,%d,%.12g,%.12g,%.12g,%.6f,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g,%.12g\n', ...
            General.Instance{i}, ...
            General.CompletedSeeds(i), ...
            General.BestObjective(i), ...
            General.BestSeed(i), ...
            General.MeanBestObjective(i), ...
            General.StdBestObjective(i), ...
            General.WorstBestObjective(i), ...
            General.MeanRuntime(i), ...
            General.MeanBasinHopImprovements(i), ...
            General.MeanBasinHopExploreImprovements(i), ...
            General.MeanBasinTriggerAttempts(i), ...
            General.MeanBasinTriggers(i), ...
            General.MeanBasinVetoes(i), ...
            General.MeanBasinExploreTriggers(i), ...
            General.MeanBasinAlignmentSamples(i), ...
            General.MeanBasinAlignmentGuidedAttempts(i), ...
            General.MeanBasinCandidateVetoes(i), ...
            General.MeanBasinRandomFallbacks(i), ...
            General.MeanEnsembleImprovements(i));
    end

    clear cleaner;
end


function value = GetSummaryField(RunSummary,fieldName)
    if isfield(RunSummary,fieldName)
        value = RunSummary.(fieldName);
    else
        value = nan;
    end
end
